import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, rm, readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createHash} from 'node:crypto';
import {createApp} from '../server/app.js';
const sha = b => createHash('sha256').update(b).digest('hex');
test('HTTP: out-of-order, retry, resume, missing chunk, hash validation and raw streaming', async t => {
 const dir=await mkdtemp(join(tmpdir(),'upload-test-')); const server=createApp({dataDir:dir});
 await new Promise(r=>server.listen(0,'127.0.0.1',r)); const base=`http://127.0.0.1:${server.address().port}`;
 t.after(async()=>{await new Promise(r=>server.close(r));await rm(dir,{recursive:true,force:true});});
 const req=async(path,method='GET',body)=>{const res=await fetch(base+path,{method,body:body instanceof Uint8Array?body:body?JSON.stringify(body):undefined,headers:body && !(body instanceof Uint8Array)?{'Content-Type':'application/json'}:{}});return {status:res.status,...await res.json()};};
 const data=Buffer.from('hello chunked world!');const meta={name:'../测试.bin',size:data.length,chunkSize:8,sha256:sha(data)};
 const init=await req('/api/uploads','POST',meta);assert.equal(init.status,200);const id=init.id;
 assert.equal((await req(`/api/uploads/${id}/complete`,'POST')).status,409);
 assert.equal((await req(`/api/uploads/${id}/chunks/2`,'PUT',data.subarray(16))).status,200);
 assert.equal((await req(`/api/uploads/${id}/chunks/0`,'PUT',data.subarray(0,8))).status,200);
 assert.equal((await req('/api/uploads','POST',meta)).uploaded.length,2);
 assert.equal((await req(`/api/uploads/${id}/chunks/0`,'PUT',data.subarray(0,8))).status,200);
 assert.equal((await req(`/api/uploads/${id}/chunks/1`,'PUT',Buffer.from('bad'))).status,400);
 assert.equal((await req(`/api/uploads/${id}/chunks/1`,'PUT',data.subarray(8,16))).status,200);
 const done=await req(`/api/uploads/${id}/complete`,'POST');assert.equal(done.status,200);assert.equal(done.sha256,sha(data));assert.deepEqual(await readFile(join(dir,'files',id)),data);
 assert.equal((await req(`/api/uploads/${id}/complete`,'POST')).sha256,sha(data));
 const bad=await req('/api/uploads','POST',{...meta,sha256:'a'.repeat(64)});
 for(let i=0;i<3;i++) await req(`/api/uploads/${bad.id}/chunks/${i}`,'PUT',data.subarray(i*8,(i+1)*8));
 assert.equal((await req(`/api/uploads/${bad.id}/complete`,'POST')).status,422);
 const raw=await req(`/api/raw?name=raw.bin&size=${data.length}&sha256=${sha(data)}`,'POST',data);assert.equal(raw.sha256,sha(data));assert.equal(raw.size,data.length);
 const empty=await req('/api/uploads','POST',{name:'empty',size:0,chunkSize:8,sha256:sha('')});assert.equal((await req(`/api/uploads/${empty.id}/complete`,'POST')).sha256,sha(''));
 for(const size of [-1,1.5,Number.MAX_SAFE_INTEGER+1]) assert.equal((await req('/api/uploads','POST',{...meta,size})).status,400);
 assert.equal((await req('/api/uploads','POST',{...meta,chunkSize:0})).status,400);
 assert.equal((await req(`/api/uploads/${id}/chunks/999`,'PUT',data)).status,400);
 assert.equal((await req('/api/uploads/not-an-id/complete','POST')).status,404);
});
